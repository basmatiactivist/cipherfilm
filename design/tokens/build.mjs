#!/usr/bin/env node
// Writes the design tokens (design/tokens/tokens.json) into each client's own form:
//   web/src/tokens.css                      CSS custom properties, dark under prefers-color-scheme
//   mobile/src/tokens.ts                    palettes and scales for the react-native-paper theme
//   mac/Sources/Cipherfilm/Tokens.swift     Ink colors (light/dark), radii, spacing and fonts for SwiftUI
// and checks every contrast pair the JSON lists, in both modes.
//   node design/tokens/build.mjs           write the files
//   node design/tokens/build.mjs --check   fail if a file is out of date or a pair falls short (for tests and CI)
// No dependencies: plain Node.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "../..");
const T = JSON.parse(readFileSync(join(root, "design/tokens/tokens.json"), "utf8"));
const check = process.argv.includes("--check");
const HEAD = "Generated by design/tokens/build.mjs from design/tokens/tokens.json. Do not edit; change the JSON and rebuild.";

const entries = (o) => Object.entries(o).filter(([k]) => !k.startsWith("$"));
const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const colors = entries(T.color);
const stage = entries(T.stage);
const types = entries(T.type);

/** [r, g, b, a] from #rrggbb or rgba(r, g, b, a). */
function rgba(c) {
  if (c.startsWith("#")) return [1, 3, 5].map((i) => parseInt(c.slice(i, i + 2), 16)).concat(1);
  const m = c.match(/[\d.]+/g).map(Number);
  return [m[0], m[1], m[2], m[3] ?? 1];
}

// ---- contrast ----
function lum([r, g, b]) {
  const f = (v) => { v /= 255; return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4; };
  return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b);
}
const ratio = (a, b) => { const x = lum(rgba(a)), y = lum(rgba(b)); return (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05); };
const problems = [];
for (const mode of ["light", "dark"]) {
  for (const [fg, bg, min] of T.contrast.pairs) {
    const r = ratio(T.color[fg][mode], T.color[bg][mode]);
    if (r < min) problems.push(`${mode}: ${fg} on ${bg} is ${r.toFixed(2)}:1, needs ${min}:1`);
  }
}

// ---- web ----
const px = (n) => `${+(n / 16).toFixed(4)}rem`;
function css() {
  const L = [`/* ${HEAD} */`, ":root {", "  color-scheme: light;"];
  for (const [k, v] of colors) L.push(`  --${k}: ${v.light};`);
  for (const [k, v] of stage) L.push(`  --${k}: ${v.value};`);
  L.push(`  --serif: ${T.font.serif.web};`, `  --font: ${T.font.sans.web};`);
  for (const [k, v] of types) {
    L.push(`  --text-${k}: ${px(v.web)};`);
    if (v.webCompact) L.push(`  --text-${k}-compact: ${px(v.webCompact)};`); // phones (under 860 px)
  }
  for (const [k, v] of entries(T.space)) L.push(`  --space-${k}: ${v}px;`);
  for (const [k, v] of entries(T.radius)) L.push(`  --radius-${k}: ${v}px;`);
  for (const [k, v] of entries(T.size)) if (!k.endsWith("-mac") && k !== "touch-android") L.push(`  --${k}: ${typeof v.value === "number" ? v.value + "px" : v.value};`);
  for (const [k, v] of entries(T.elevation)) L.push(`  --shadow-${k}: ${v.web};`);
  L.push(`  --fast: ${T.motion.fast.ms / 1000}s;`, `  --medium: ${T.motion.medium.ms / 1000}s;`);
  L.push(`  --turn: ${T.motion.turn.ms / 1000}s;`, `  --seal: ${T.motion.seal.ms / 1000}s;`, `  --breathe: ${T.motion.breathe.ms / 1000}s;`);
  L.push(`  --ease-out: ${T.motion["ease-out"].value};`, `  --ease-standard: ${T.motion["ease-standard"].value};`);
  L.push("}", "@media (prefers-color-scheme: dark) {", "  :root {", "    color-scheme: dark;");
  for (const [k, v] of colors) L.push(`    --${k}: ${v.dark};`);
  L.push("  }", "}", "");
  return L.join("\n");
}

// ---- Android ----
function ts() {
  const pal = (mode) => colors.map(([k, v]) => `  ${camel(k)}: ${JSON.stringify(v[mode])},`).join("\n");
  const keys = colors.map(([k]) => camel(k));
  const typ = types.map(([k, v]) => {
    const fam = T.font[v.family].android;
    const lh = Math.round(v.android * (v.lineHeight ?? 1.25));
    return `  ${k}: { ${fam ? `fontFamily: ${JSON.stringify(fam)}, ` : ""}fontSize: ${v.android}, lineHeight: ${lh}, fontWeight: "${v.weight}" as const, letterSpacing: 0 },`;
  }).join("\n");
  return `// ${HEAD}
// Colors are the same roles as the web's CSS variables and the Mac's Ink, in camelCase.

export interface Palette {
${keys.map((k) => `  ${k}: string;`).join("\n")}
}

export const light: Palette = {
${pal("light")}
};

export const dark: Palette = {
${pal("dark")}
};

/** The photo viewer: black in both modes. */
export const stage = {
${stage.map(([k, v]) => `  ${camel(k)}: ${JSON.stringify(v.value)},`).join("\n")}
} as const;

/** Type roles in sp (Android's base is 16). The serif is for time and place only. */
export const text = {
${typ}
} as const;

export const space = { ${entries(T.space).map(([k, v]) => `s${k}: ${v}`).join(", ")} } as const;
export const radius = { ${entries(T.radius).map(([k, v]) => `${k}: ${v}`).join(", ")} } as const;
export const touch = ${T.size["touch-android"].value};
export const motion = { fast: ${T.motion.fast.ms}, medium: ${T.motion.medium.ms}, turn: ${T.motion.turn.ms}, seal: ${T.motion.seal.ms}, breathe: ${T.motion.breathe.ms} } as const;
/** The loading badge (Loader.tsx): inline and on its own, in dp. */
export const loader = { small: ${T.size.loader.value}, large: ${T.size["loader-large"].value} } as const;
`;
}

// ---- Mac ----
function swift() {
  const hex = (c) => { const [r, g, b] = rgba(c); return "0x" + [r, g, b].map((v) => v.toString(16).padStart(2, "0")).join("").toUpperCase(); };
  const alpha = (c) => rgba(c)[3];
  const col = colors.map(([k, v]) => {
    const a = [alpha(v.light), alpha(v.dark)];
    return `  static let ${camel(k)} = c(${hex(v.light)}, ${hex(v.dark)}${a[0] !== 1 || a[1] !== 1 ? `, alpha: ${a[0]}, ${a[1]}` : ""})`;
  }).join("\n");
  const stg = stage.map(([k, v]) => `  static let ${camel(k)} = c(${hex(v.value)}, ${hex(v.value)}${alpha(v.value) !== 1 ? `, alpha: ${alpha(v.value)}, ${alpha(v.value)}` : ""})`).join("\n");
  const font = types.map(([k, v]) => {
    const w = { 400: "", 600: ", weight: .semibold", 700: ", weight: .bold" }[v.weight];
    return v.family === "serif" ? `  static let ${k} = Font.custom(${JSON.stringify(T.font.serif.mac)}, size: ${v.mac})` : `  static let ${k} = Font.system(size: ${v.mac}${w})`;
  }).join("\n");
  return `// ${HEAD}
import SwiftUI

/** The color roles, light and dark (see Theme.swift for how they resolve). */
extension Ink {
${col}

  // the photo viewer: black in both modes
${stg}
}

/** Type roles in points (macOS's base is 13). Serif only for time and place. */
enum Typo {
${font}

  enum Size {
${types.map(([k, v]) => `    static let ${k}: CGFloat = ${v.mac}`).join("\n")}
  }
}

enum Space {
${entries(T.space).map(([k, v]) => `  static let s${k}: CGFloat = ${v}`).join("\n")}
}

enum Radius {
${entries(T.radius).filter(([k]) => k !== "round").map(([k, v]) => `  static let ${k}: CGFloat = ${v}`).join("\n")}
}

enum Metric {
  static let control: CGFloat = ${T.size["control-mac"].value}
  static let field: CGFloat = ${T.size["field-mac"].value}
  static let menuShadowRadius: CGFloat = ${T.elevation.menu.radius}
  static let menuShadowY: CGFloat = ${T.elevation.menu.y}
  static let loader: CGFloat = ${T.size["loader-mac"].value}
  static let loaderLarge: CGFloat = ${T.size["loader-large-mac"].value}
}

enum Motion {
  static let fast: Double = ${T.motion.fast.ms / 1000}
  static let medium: Double = ${T.motion.medium.ms / 1000}
  static let turn: Double = ${T.motion.turn.ms / 1000}
  static let seal: Double = ${T.motion.seal.ms / 1000}
  static let breathe: Double = ${T.motion.breathe.ms / 1000}
}
`;
}

const out = {
  "web/src/tokens.css": css(),
  "mobile/src/tokens.ts": ts(),
  "mac/Sources/Cipherfilm/Tokens.swift": swift(),
};
let stale = [];
for (const [f, text] of Object.entries(out)) {
  const p = join(root, f);
  let cur = null;
  try { cur = readFileSync(p, "utf8"); } catch {}
  if (cur === text) continue;
  if (check) stale.push(f); else { writeFileSync(p, text); console.log(`wrote ${f}`); }
}
for (const p of problems) console.error(`contrast: ${p}`);
for (const f of stale) console.error(`out of date: ${f} (run node design/tokens/build.mjs)`);
if (problems.length || stale.length) process.exit(1);
console.log(`tokens ok: ${colors.length} color roles, ${T.contrast.pairs.length} contrast pairs pass in light and dark`);
