describe("QR encoder", () => {
  for (const v of VECTORS) {
    it(`matches the decoded vector (version ${v.version})`, () => {
      const q = encodeQR(v.text);
      expect(q.version).toBe(v.version);
      expect(q.mask).toBe(v.mask);
      expect(q.modules.map((r) => r.map((b) => (b ? "1" : "0")).join(""))).toEqual(v.rows);
    });
  }
  it("picks the smallest version that fits, and grows", () => {
    expect(encodeQR("a".repeat(14)).version).toBe(1); // level M, byte mode: 14 bytes fit version 1
    expect(encodeQR("a".repeat(15)).version).toBe(2);
    expect(encodeQR("a".repeat(2331)).version).toBe(40);
    expect(() => encodeQR("a".repeat(2332))).toThrow();
  });
  it("draws the finder patterns and the dark module", () => {
    const q = encodeQR("otpauth://totp/x");
    const n = q.size;
    for (const [x, y] of [[0, 0], [n - 7, 0], [0, n - 7]]) {
      for (let i = 0; i < 7; i++) expect(q.modules[y][x + i] && q.modules[y + i][x]).toBe(true);
      expect(q.modules[y + 1][x + 1]).toBe(false);
      expect(q.modules[y + 3][x + 3]).toBe(true);
    }
    expect(q.modules[n - 8][8]).toBe(true);
  });
  it("chooses the mask with the lowest penalty", () => {
    const text = "otpauth://totp/Cipherfilm:a%40b.org?secret=ABCDEFGHIJKLMNOPQRSTUVWXYZ234567";
    const best = encodeQR(text);
    for (let m = 0; m < 8; m++) expect(penalty(encodeQR(text, { mask: m }).modules)).toBeGreaterThanOrEqual(penalty(best.modules));
  });
  it("makes an SVG path with a quiet zone", () => {
    const q = encodeQR("hi");
    const d = qrPath(q);
    expect(d.startsWith("M4 4h1v1h-1z")).toBe(true);
    expect(d.match(/M/g)!.length).toBe(q.modules.flat().filter(Boolean).length);
  });
});
